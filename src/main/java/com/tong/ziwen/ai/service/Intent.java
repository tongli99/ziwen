package com.tong.ziwen.ai.service;

/**
 * 分诊意图：RouterAgent 对每轮问句的三分类结果，编排层按它决定这轮交给哪个分身接。
 *
 * <p>分类边界刻意只看问句本身：拿不准的一律归 {@link #CHAT}——闲聊分支背后是
 * 全工具的全能伴读，分错了顶多损失专才短说明书的收益，不会接不住。</p>
 *
 * <p>下面每个值的注释是给开发者看的摘要；模型看不到它们，生效的判据只有一份，
 * 在 prompts/router-prompt.txt 里，两处不一致时以那份文件为准。</p>
 */
public enum Intent {

    /** 背诗：问具体的古诗——背全诗、背不全、问出处、问作者、问哪一课学的、问诗里的字词意思。 */
    POEM,

    /** 查字：问具体生字的出处（哪一课学的、几画、什么偏旁），或要某课的预习字表。 */
    HANZI,

    /** 闲聊：其余全部——陪聊、问词语意思、阅读写作求助，以及拿不准归类的句子。 */
    CHAT
}
